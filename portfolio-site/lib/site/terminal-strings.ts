/** The shape every language has to fill. Widened: string literals become `string`. */
type Widen<T> = { -readonly [K in keyof T]: T[K] extends (...a: infer A) => string ? (...a: A) => string : T[K] extends readonly string[] ? readonly string[] : string };
export type TerminalStrings = Widen<typeof en>;
export type StringKey = keyof TerminalStrings;
export const STRINGS: Record<Lang, TerminalStrings> = { en, bn, hi };

/** One string, in `lang`; a key the language lacks falls back to English (and says so in development). */
export function t<K extends StringKey>(key: K, lang: Lang): TerminalStrings[K] {
  const v = STRINGS[lang]?.[key];
  if (v !== undefined) return v;
  if (process.env.NODE_ENV !== "production") console.warn(`[terminal-strings] "${key}" is missing in "${lang}"`);
  return STRINGS.en[key];
}
