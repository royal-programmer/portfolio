// One-off (round 25, E2): copy the API Test Center product assets into public/projects/api-test-center/.
// The main poster and the screenshots become 1280-wide WebP (quality 80); the clips and their posters are copied as they are.
// The source folder is read only. `demo.webm` and `report-light.png` are not copied.
// Round 26 (F5): every image also gets a tiny blur-up placeholder (a 20 px wide WebP as a data URI), written to
// lib/site/netflix-lqip.ts, keyed by its public path. `--lqip` makes only the placeholders, from the files already in public/
// (the source folder is not needed for that).
// Run from portfolio-site/: node scripts/netflix-media.mjs [source-assets-folder]  |  node scripts/netflix-media.mjs --lqip
import { copyFileSync, mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import sharp from "sharp";

const ONLY_LQIP = process.argv.includes("--lqip");
const SRC = process.argv.find((a, i) => i >= 2 && !a.startsWith("--")) ?? "C:/Users/ratul.roy/Desktop/Process APIs/ApiTestCenter/website/assets";
const OUT = join(process.cwd(), "public/projects/api-test-center");
if (!ONLY_LQIP) {
  mkdirSync(join(OUT, "screens"), { recursive: true });
  mkdirSync(join(OUT, "clips"), { recursive: true });
}

const webp = async (from, to) => {
  await sharp(from).resize({ width: 1280, withoutEnlargement: true }).webp({ quality: 80 }).toFile(to);
  console.log(to.replace(OUT, ""), Math.round(statSync(to).size / 1024), "KB");
};

if (!ONLY_LQIP) {
  await webp(join(SRC, "demo-poster.jpg"), join(OUT, "poster.webp"));
  for (const n of ["builder", "chain", "charts", "help", "report", "send"]) await webp(join(SRC, "screens", `${n}.png`), join(OUT, "screens", `${n}.webp`));
  for (const n of ["collection", "history", "load-test", "send", "sign-in", "upload", "websocket"]) {
    for (const ext of ["webm", "jpg"]) copyFileSync(join(SRC, "clips", `${n}.${ext}`), join(OUT, "clips", `${n}.${ext}`));
  }
}

// The placeholders: one entry per poster, screenshot and clip poster under public/projects/.
const PUBLIC = join(process.cwd(), "public");
const lqip = {};
const walk = async (dir) => {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) await walk(full);
    else if (/\.(webp|jpg|png)$/i.test(name)) {
      const buf = await sharp(full).resize({ width: 20 }).webp({ quality: 40 }).toBuffer();
      lqip["/" + full.slice(PUBLIC.length + 1).replaceAll("\\", "/")] = `data:image/webp;base64,${buf.toString("base64")}`;
    }
  }
};
await walk(join(PUBLIC, "projects"));
writeFileSync(
  join(process.cwd(), "lib/site/netflix-lqip.ts"),
  `// Generated by scripts/netflix-media.mjs (F5): blur-up placeholders, 20 px wide, keyed by public path. Do not edit.
export const LQIP: Record<string, string> = ${JSON.stringify(lqip, null, 2)};
`,
);
console.log("lqip", Object.keys(lqip).length, "images");
console.log("done");
